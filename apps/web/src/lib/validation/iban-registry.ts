export const IBAN_GLOBAL_MIN = 15;
export const IBAN_GLOBAL_MAX = 34;

/** Max characters (digits/letters) while typing; narrows once a known country prefix is present. */
export function ibanInputMaxLength(cleanedUpperAlnum: string): number {
  if (cleanedUpperAlnum.length < 2) return IBAN_GLOBAL_MAX;
  const a = cleanedUpperAlnum[0];
  const b = cleanedUpperAlnum[1];
  if (a >= 'A' && a <= 'Z' && b >= 'A' && b <= 'Z') {
    const n = IBAN_LENGTH_BY_COUNTRY[a + b];
    if (n !== undefined) return n;
  }
  return IBAN_GLOBAL_MAX;
}

export function ibanExpectedLengthForCountry(countryCode: string): number | undefined {
  return IBAN_LENGTH_BY_COUNTRY[countryCode];
}
